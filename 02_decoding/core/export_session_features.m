function export_session_features(session, condition, manifest, bands, basis, destination)
%EXPORT_SESSION_FEATURES  Export causal decoder features using the study settings.
% Set GAIT_TRIPLE_ROOT to the causal EEG, event and goniometer triples.
% Supply the band table appropriate to the training trials of the intended fold.
% MATLAB exports features. Python fits the 30-component readout on these features.
old_dir = getenv('CP_EXPORT_DIR');
old_only = getenv('CP_EXPORT_ONLY');
cleanup = onCleanup(@() restore_export(old_dir, old_only));
setenv('CP_EXPORT_DIR', destination);
setenv('CP_EXPORT_ONLY', '1');
grid = [1e-3 1e-2 0.1 1 10 100];
run_decoder('session_manifest', manifest, 'sessions', {session}, 'condition', condition, ...
    'out_dir', destination, 'outer_k', 10, 'inner_k', 10, 'outer_folds', 1:10, 'cv_mode', 'random', ...
    'feature_mode', 'delta_fold_diagwhiten_shared_pca', 'shared_pca_file', basis, ...
    'shared_pca_components', 20, 'shared_pca_scaler_scope', 'fold', 'eeg_baseline_mode', 'mean', ...
    'bp_lo', 0.1, 'bp_hi', 2, 'bp_band_csv', bands, 'bp_band_harmonic_k_list', [1 2 3], ...
    'bp_band_feature_mode', 'cdm_o1_c0p18_causal', 'lag_ms', -2000:50:0, 'alpha_grid', 0, ...
    'phase_recon', 'delay_template', 'phase_target_mode', 'phase_pj', 'lambda_mode', 'scalar', ...
    'lambda_grid', grid, 'stage1_lambda_mode', 'innercv', 'post_mode', 'prediction_fir_cvlambda', ...
    'post_lambda', 1, 'post_lambda_grid', grid, 'post_inner_k', 10, 'post_guard_margin', 0, ...
    'post_fir_lag_ms', -2000:50:0, 'post_fir_lag_unit', 'ms', 'post_fir_causal_only', true, ...
    'diag_plot_pca', false, 'diag_max_trials', 0, 'valid_from_sec', 0, 'min_trial_sec', 0, 'post_train_from_sec', 0);
end

function restore_export(destination, flag)
setenv('CP_EXPORT_DIR', destination);
setenv('CP_EXPORT_ONLY', flag);
end
